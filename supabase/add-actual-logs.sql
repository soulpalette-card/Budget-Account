-- ============================================================================
-- 给记录加「累计实际记录」列（累计项功能）
-- ----------------------------------------------------------------------------
-- Supabase → SQL Editor → New query → 粘贴 → Run。跑一次即可，可重复跑。
-- 加一列 actual_logs（jsonb）：存一个预算项下面「每天的实际花费」，例如
--   OT买饭 预算 2000，actual_logs = [{"date":"2026-07-01","amount":80},
--                                    {"date":"2026-07-02","amount":100}, ...]
--   这样预算金额不变，实际按天累加，随时算出「剩余 = 预算 − 已花」。
-- 普通（一次性）的记录，这一列是空（null），完全不受影响。
-- ============================================================================

alter table public.entries
  add column if not exists actual_logs jsonb;
