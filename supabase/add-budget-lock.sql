-- ============================================================================
-- 给月份加「预算锁定」开关
-- ----------------------------------------------------------------------------
-- Supabase → SQL Editor → New query → 粘贴 → Run。跑一次即可，可重复跑。
-- 加一列 budget_locked（默认 false）：
--   锁定后，规划栏冻结不能改，新记的每一笔自动进「临时增加」。
-- ============================================================================

alter table public.months
  add column if not exists budget_locked boolean not null default false;
