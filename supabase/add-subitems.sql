-- ============================================================================
-- 给记录加「子项目/明细」列（拆单功能）
-- ----------------------------------------------------------------------------
-- Supabase → SQL Editor → New query → 粘贴 → Run。跑一次即可，可重复跑。
-- 加一列 sub_items（jsonb）：存一笔账里的多张小单据，例如
--   office expenses 9150 = [{"desc":"复印机","amount":5000},{"desc":"电话费","amount":4150}]
-- 没有子项目的记录，这一列就是空（null），完全不影响。
-- ============================================================================

alter table public.entries
  add column if not exists sub_items jsonb;
